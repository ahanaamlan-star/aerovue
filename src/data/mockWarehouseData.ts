function enrichDiscrepancy(d: any): DiscrepancyRecord {
  const requiresHumanVerification = d.confidence.overall < 85;
  const consecutiveCount = d.persistence?.scanCount || 1;
  const isPersistent = d.persistence?.isPersistent || consecutiveCount >= 2;
  const lifecycle: TemporalLifecycle = d.temporalLifecycle || (isPersistent ? 'PERSISTENT' : 'NEW');
  const persistenceScore =
    d.persistenceScore ||
    (lifecycle === 'PERSISTENT' ? (consecutiveCount >= 3 ? 90 : 70) : lifecycle === 'INTERMITTENT' ? 55 : 35);
  const persistenceExplanation =
    d.persistenceExplanation ||
    (lifecycle === 'PERSISTENT'
      ? `Similar discrepancy observed in ${consecutiveCount} consecutive scans.`
      : lifecycle === 'INTERMITTENT'
      ? `Discrepancy observed intermittently across multiple scan sessions (${consecutiveCount} occurrences).`
      : 'First detected in current scan epoch. Temporal baseline initializing.');
  const persistenceDisclaimer =
    'This increases prioritization confidence but does not independently establish the root cause.';

  return {
    ...d,
    discrepancyId: d.id,
    zone: d.location.zone,
    rack: d.location.rack,
    shelf: d.location.shelf,
    bin: d.location.bin,
    sku: d.expectedSku || d.observedSku || 'UNKNOWN',
    expectedValue: d.expectedQuantity,
    observedValue: d.observedQuantity,
    difference: d.quantityDelta,
    type: d.discrepancyType,
    visionConfidence: d.confidence.visionConfidence,
    spatialConfidence: d.confidence.spatialConfidence,
    temporalScore: d.confidence.temporalConfidence,
    severity: d.risk.severityFactor,
    riskScore: d.risk.score,
    status: requiresHumanVerification
      ? 'REQUIRES HUMAN VERIFICATION'
      : lifecycle === 'PERSISTENT'
      ? 'PERSISTENT'
      : 'FLAGGED',
    requiresHumanVerification,
    temporalLifecycle: lifecycle,
    persistenceScore,
    persistenceExplanation,
    persistenceDisclaimer,
    persistence: {
      ...d.persistence,
      persistenceScore,
      lifecycleState: lifecycle,
    },
  };
}

